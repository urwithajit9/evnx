use crate::core::converter::{ConvertOptions, Converter};
use anyhow::Result;
// use std::collections::HashMap;
use indexmap::IndexMap;

/// `--to terraform`: a `.tfvars` file of assignments, or with
/// `declarations` a `.tf` file of `variable` blocks (`--terraform-declarations`).
#[derive(Debug, Clone, Copy, Default)]
pub struct TerraformConverter {
    /// Emit `variable` blocks instead of the values.
    pub declarations: bool,
}

impl Converter for TerraformConverter {
    /// Names keep the case the `.env` (or `--transform`) gives them: Terraform
    /// names are case-sensitive, and lowercasing them ignored `--transform`
    /// and merged `A_B` with `a_b` (RM-65, I-093).
    ///
    /// The default output is `name = "value"` lines, for a `.tfvars` file that
    /// stays out of git. ⛔ The declarations never carry the value of a secret
    /// as a `default`: a `.tf` file is the one people commit.
    fn convert(&self, vars: &IndexMap<String, String>, options: &ConvertOptions) -> Result<String> {
        let mut output = String::new();
        output.push_str("# Generated by evnx\n");
        if self.declarations {
            output.push_str("# Variable declarations. A secret has no default: supply its value\n");
            output.push_str(
                "# from the .tfvars output of `evnx convert --to terraform`, or TF_VAR_<name>.\n",
            );
        }
        output.push('\n');

        for (key, value) in options.prepare(vars, self)? {
            // ⛔ `${` and `%{` are HCL interpolation and directive markers, and
            // escaping only `\` and `"` left them live — so a value containing
            // `${…}` referred to a variable that does not exist and the
            // generated file failed to load.
            if !self.declarations {
                output.push_str(&format!(
                    "{} = {}\n",
                    key,
                    crate::formats::quoting::hcl_string(value.as_str())
                ));
                continue;
            }
            let secret = crate::core::classify::holds_secret(&key, &value);
            output.push_str(&format!("variable \"{key}\" {{\n  type = string\n"));
            if secret {
                output.push_str("  sensitive = true\n");
            } else {
                output.push_str(&format!(
                    "  default = {}\n",
                    crate::formats::quoting::hcl_string(value.as_str())
                ));
            }
            output.push_str("}\n\n");
        }
        if self.declarations {
            while output.ends_with("\n\n") {
                output.pop();
            }
        }

        Ok(output)
    }

    fn name(&self) -> &str {
        "terraform"
    }

    fn description(&self) -> &str {
        "Terraform .tfvars format"
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn run(declarations: bool) -> String {
        let mut vars = IndexMap::new();
        vars.insert("Api_Key".to_string(), "abc123def456ghi789".to_string());
        vars.insert("PORT".to_string(), "8080".to_string());
        TerraformConverter { declarations }
            .convert(&vars, &ConvertOptions::default())
            .unwrap()
    }

    #[test]
    fn tfvars_keeps_case() {
        let out = run(false);
        assert!(out.contains("Api_Key = \"abc123def456ghi789\""), "{out}");
        assert!(out.contains("PORT = \"8080\""), "{out}");
    }

    #[test]
    fn declarations_never_carry_a_secret() {
        let out = run(true);
        assert!(out.contains("variable \"Api_Key\" {"), "{out}");
        assert!(out.contains("sensitive = true"), "{out}");
        assert!(!out.contains("abc123def456ghi789"), "{out}");
        assert!(out.contains("default = \"8080\""), "{out}");
    }
}
