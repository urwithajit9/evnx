//! The files `evnx init` writes are a contract. These tests pin them byte for byte.
//!
//! # Why this exists
//!
//! `.env.example` is committed and read by other tools (`validate`, `sync`,
//! `doctor`, a teammate's editor), and `.gitignore` decides whether a secret can
//! be committed. A change to either should be a decision someone made, not a side
//! effect of a refactor. The 0.10.1 work on `init` changes some of these files on
//! purpose (framework-aware client variables, the `Auth` section, the append
//! stamp); every such change has to show up here as a reviewed diff.
//!
//! What is pinned: `.env.example`, `.env` and `.gitignore` for blank, a named
//! component list, **every** blueprint, `--detect` and `--from-source` (fresh
//! and appending). What is not: terminal output, which is human-facing and meant
//! to change (`tests/golden_output.rs` follows the same rule). Specific messages
//! are pinned only where a defect is known, in `init_integration.rs`'s `known_*`
//! tests.
//!
//! # Updating
//!
//! ```bash
//! UPDATE_GOLDEN=1 cargo test --all-features --test init_golden
//! git diff tests/golden/init/      # read every line before committing
//! ```
//!
//! ⚠️ A diff here is either a bug or a decision. If it is a decision, name it
//! (the `CH-INIT-nn` entry or the issue id) in the commit message.

use assert_cmd::cargo::cargo_bin_cmd;
use std::fs;
use std::path::{Path, PathBuf};
use tempfile::TempDir;

/// Every blueprint id, in the order `evnx init --blueprint <unknown>` lists them.
/// `blueprint_list_matches_the_binary` keeps this in step with the schema, so a
/// new blueprint fails loudly here until it has a golden file of its own.
const BLUEPRINTS: &[&str] = &[
    "t3_modern",
    "mern_v2",
    "fastapi_ai",
    "rust_high_perf",
    "laravel_monolith",
    "go_microservice",
    "supabase_fullstack",
    "django_enterprise",
    "firebase_mobile",
    "content_marketing",
];

/// Blank out what legitimately differs between runs: the date and version in
/// the footer `init` writes and in the stamp an append writes.
///
/// `# Generated by evnx v0.10.0 on 2026-10-13 02:58` and
/// `# Added by evnx add on 2026-10-13 02:59` keep their wording (that is part of
/// the contract, I-009) and lose only the clock and the version.
fn normalise(raw: &str) -> String {
    let mut out = String::with_capacity(raw.len());
    for line in raw.lines() {
        let line = if line.starts_with("# Generated by evnx ") {
            "# Generated by evnx <version> on <date>".to_string()
        } else if let Some(at) = line.strip_prefix("# read at ") {
            // `--from-source` records where it saw a name with the platform's
            // separator (`src\config.ts:1` on Windows, by design; see the test
            // in `init/source.rs`). The golden pins the location, not the OS.
            format!("# read at {}", at.replace('\\', "/"))
        } else if line.starts_with("# Added by evnx ") {
            match line.rsplit_once(" on ") {
                Some((head, _date)) => format!("{head} on <date>"),
                None => line.to_string(),
            }
        } else {
            line.to_string()
        };
        out.push_str(&line);
        out.push('\n');
    }
    out
}

fn golden_path(name: &str) -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("tests/golden/init")
        .join(name)
}

/// Compare against the golden file, or rewrite it under `UPDATE_GOLDEN=1`.
/// Both sides are normalised, so a CRLF checkout cannot fail it (see
/// `golden_output.rs` for why that matters on Windows).
fn check(name: &str, actual_raw: &str) {
    let actual = normalise(actual_raw);
    let path = golden_path(name);

    if std::env::var_os("UPDATE_GOLDEN").is_some() {
        fs::create_dir_all(path.parent().unwrap()).unwrap();
        fs::write(&path, &actual).unwrap();
        return;
    }

    let expected = fs::read_to_string(&path)
        .map(|s| normalise(&s))
        .unwrap_or_else(|_| {
            panic!(
                "missing golden file {}\n\n\
                 Create it with:  UPDATE_GOLDEN=1 cargo test --all-features --test init_golden",
                path.display()
            )
        });

    assert_eq!(
        expected, actual,
        "\n\n{name} changed.\n\n\
         This is a file `evnx init` writes into a user's project. A diff here is either\n\
         a bug or a deliberate decision. If it is deliberate, regenerate with\n\
         UPDATE_GOLDEN=1 and name the decision (CH-INIT-nn / issue id) in the commit.\n"
    );
}

fn read(dir: &Path, file: &str) -> String {
    fs::read_to_string(dir.join(file))
        .unwrap_or_else(|e| panic!("{file} was not written in {}: {e}", dir.display()))
}

/// Run `evnx init <args>` in `dir`, which must succeed.
fn init(dir: &Path, args: &[&str]) {
    cargo_bin_cmd!("evnx")
        .current_dir(dir)
        .arg("init")
        .args(args)
        .assert()
        .success();
}

/// Pin all three files under `<prefix>.env.example`, `<prefix>.env`,
/// `<prefix>.gitignore`.
fn check_all_three(prefix: &str, dir: &Path) {
    check(&format!("{prefix}.env.example"), &read(dir, ".env.example"));
    check(&format!("{prefix}.env"), &read(dir, ".env"));
    check(&format!("{prefix}.gitignore"), &read(dir, ".gitignore"));
}

#[test]
fn blank() {
    let d = TempDir::new().unwrap();
    init(d.path(), &["--yes"]);
    check_all_three("blank", d.path());
}

/// The Pulse tutorial's stack. I-002 (framework-aware client variables) changes
/// this file on purpose in 0.10.1; until then it pins the Next.js-flavoured
/// names a Vite stack gets today.
#[test]
fn with_vite_supabase_clerk_vercel() {
    let d = TempDir::new().unwrap();
    init(d.path(), &["--with", "vite,supabase,clerk,vercel", "--yes"]);
    check_all_three("with-vite-supabase-clerk-vercel", d.path());
}

/// One golden per blueprint (T-INIT-10). Seven of the ten had no test at all.
#[test]
fn every_blueprint() {
    for id in BLUEPRINTS {
        let d = TempDir::new().unwrap();
        init(d.path(), &["--blueprint", id, "--yes"]);
        check(
            &format!("blueprint-{id}.env.example"),
            &read(d.path(), ".env.example"),
        );
        check(&format!("blueprint-{id}.env"), &read(d.path(), ".env"));
    }
}

/// `BLUEPRINTS` must be exactly what the binary offers, or a new blueprint would
/// ship without a golden file.
#[test]
fn blueprint_list_matches_the_binary() {
    let d = TempDir::new().unwrap();
    let out = cargo_bin_cmd!("evnx")
        .current_dir(d.path())
        .args(["init", "--blueprint", "no-such-blueprint", "--yes"])
        .output()
        .unwrap();
    let text =
        String::from_utf8_lossy(&out.stderr).to_string() + &String::from_utf8_lossy(&out.stdout);

    let listed: Vec<&str> = text
        .lines()
        .skip_while(|l| !l.starts_with("Available blueprints:"))
        .skip(1)
        .take_while(|l| !l.trim().is_empty())
        .filter_map(|l| {
            let l = l.strip_prefix("  ")?;
            let id = l.split_whitespace().next()?;
            id.chars()
                .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_')
                .then_some(id)
        })
        .collect();

    assert_eq!(listed, BLUEPRINTS, "blueprint list changed:\n{text}");
}

/// The same project `init_integration.rs` uses for detection.
#[test]
fn detect_node_and_compose() {
    let d = TempDir::new().unwrap();
    fs::write(
        d.path().join("package.json"),
        r#"{"dependencies":{"next":"16","stripe":"14","@clerk/nextjs":"5"}}"#,
    )
    .unwrap();
    fs::write(
        d.path().join("docker-compose.yml"),
        "services:\n  postgres:\n    image: postgres:16\nvolumes:\n  postgres_data:\n",
    )
    .unwrap();
    init(d.path(), &["--detect"]);
    check_all_three("detect-node-compose", d.path());
}

fn sourced_project() -> TempDir {
    let d = TempDir::new().unwrap();
    fs::create_dir_all(d.path().join("src")).unwrap();
    fs::write(
        d.path().join("src/config.ts"),
        "export const a = process.env.API_TOKEN;\nexport const b = \"PUBLIC_SITE_URL\";\n",
    )
    .unwrap();
    d
}

#[test]
fn from_source_fresh() {
    let d = sourced_project();
    init(d.path(), &["--from-source", "--yes"]);
    check_all_three("from-source-fresh", d.path());
}

/// Appending to a hand-written template: the existing line must survive, and
/// the appended block's stamp is pinned (I-009 changes it on purpose).
/// `.env` and `.gitignore` are deliberately not pinned here: today neither is
/// written on this path (N-06), and `known_n06_*` in `init_integration.rs` pins
/// that absence instead.
#[test]
fn from_source_appending() {
    let d = sourced_project();
    fs::write(d.path().join(".env.example"), "HAND_WRITTEN=1\n").unwrap();
    init(d.path(), &["--from-source", "--yes"]);
    check(
        "from-source-append.env.example",
        &read(d.path(), ".env.example"),
    );
}
