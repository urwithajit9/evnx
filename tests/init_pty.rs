/// N-07 (part, group C): Esc cancels at every kind of prompt, writes nothing,
/// and exits 0. (Ctrl-C is a signal, handled separately.) A list menu cancels
/// on Esc; a yes/no question takes its answer on Enter (N-09), so there Esc
/// selects "cancel" and Enter confirms it.
#[test]
fn escape_cancels_at_every_prompt() {
    // (keys to reach the prompt, prompt text, is it a yes/no question, label)
    let cases: &[(&[&str], &str, bool, &str)] = &[
        (&[], "How do you want to start?", false, "start menu"),
        (
            &[DOWN, ENTER],
            "Choose a stack blueprint",
            false,
            "blueprint list",
        ),
        (
            &[DOWN, ENTER, ENTER],
            "Generate .env files with these variables?",
            true,
            "confirm",
        ),
        (
            &[DOWN, DOWN, ENTER],
            "Select your primary language",
            false,
            "architect",
        ),
    ];
    for (keys, prompt, yes_no, label) in cases {
        let d = TempDir::new().unwrap();
        let mut run = run_init(d.path(), &[]);
        run.wait_for("How do you want to start?");
        if !keys.is_empty() {
            run.press(keys);
            run.wait_for(prompt);
        }
        if *yes_no {
            run.cancel_yes_no();
        } else {
            run.press(&[ESC]);
        }
        let (rest, code) = run.finish();

        assert_eq!(code, 0, "{label}");
        assert!(
            rest.contains("Aborted. Nothing was written."),
            "{label}: {rest}"
        );
        assert!(!rest.contains("Next steps"), "{label}: {rest}");
        for f in [".env", ".env.example", ".gitignore"] {
            assert!(!d.path().join(f).exists(), "{label}: {f} written");
        }
    }
}

