//! `evnx init`'s menus, driven through a real pseudo-terminal.
//!
//! # Why a pty
//!
//! Every prompt in `init` is a dialoguer widget, and dialoguer refuses a stdin
//! that is not a terminal (`IO error: not a terminal`). The four tests that used
//! to cover these menus fed keys through `assert_cmd`'s `write_stdin` (a pipe),
//! modelled the menus as numbered lists ("type 1, then 0"), and were
//! `#[ignore]`d with "run manually", which could not work either (T-001). They
//! are replaced by these, which press the same keys a person would.
//!
//! Unix only: the Windows console is a different mechanism, and `expectrl` is a
//! `cfg(unix)` dev-dependency.
//!
//! Defects are pinned first as `known_*` tests and flipped by the PR that fixes
//! them (see `init_integration.rs` for the convention). Those in this file were
//! all fixed in 0.10.1.
#![cfg(unix)]

mod support;

use assert_cmd::cargo::cargo_bin_cmd;
use std::path::Path;
use std::time::Duration;
use support::pty::{Pty, CTRL_C, DOWN, ENTER, ESC, SPACE};
use tempfile::TempDir;

/// One interactive `evnx init <args>` in `dir`. The driver itself is shared,
/// in `tests/support/pty.rs`.
fn run_init(dir: &Path, args: &[&str]) -> Pty {
    let mut full = vec!["init"];
    full.extend_from_slice(args);
    Pty::spawn(dir, &full)
}

/// `.env.example` without the dated footer.
fn example_body(dir: &Path) -> String {
    std::fs::read_to_string(dir.join(".env.example"))
        .expect(".env.example written")
        .lines()
        .filter(|l| !l.starts_with("# Generated by evnx"))
        .collect::<Vec<_>>()
        .join("\n")
}

/// The same template written non-interactively, for comparison.
fn example_via_flags(args: &[&str]) -> String {
    let d = TempDir::new().unwrap();
    cargo_bin_cmd!("evnx")
        .current_dir(d.path())
        .arg("init")
        .args(args)
        .arg("--yes")
        .assert()
        .success();
    example_body(d.path())
}

