/// Replaces `init_blueprint_specific_t3_modern` and
/// `init_interactive_mode_selection`. Blueprint → first stack → confirm writes
/// exactly what `--blueprint t3_modern` writes.
#[test]
fn blueprint_from_the_menu_equals_the_flag() {
    let d = TempDir::new().unwrap();
    let mut run = Run::start(d.path(), &[]);

    run.wait_for("How do you want to start?");
    run.press(&[DOWN, ENTER]); // Blueprint (Blank is pre-selected since 0.10.1)
    run.wait_for("Choose a stack blueprint");
    run.press(&[ENTER]); // T3 Turbo, first in the list
    run.wait_for("Preview:");
    run.wait_for("Generate .env files with these variables?");
    run.press(&["y", ENTER]);
    let (_, code) = run.finish();

    assert_eq!(code, 0);
    assert_eq!(
        example_body(d.path()),
        example_via_flags(&["--blueprint", "t3_modern"])
    );
    assert!(d.path().join(".env").exists());
    assert!(d.path().join(".gitignore").exists());
}

/// Replaces `init_architect_interactive` (T-INIT-18). Architect with Vite,
/// Supabase, Clerk and Vercel writes byte for byte what `--with` writes, although
/// the two go through different resolvers.
#[test]
fn architect_from_the_menu_equals_with() {
    let d = TempDir::new().unwrap();
    let mut run = Run::start(d.path(), &[]);

    run.wait_for("How do you want to start?");
    run.press(&[DOWN, DOWN, ENTER]); // Architect
    run.wait_for("Select your primary language");
    run.press(&[ENTER]); // JavaScript / TypeScript
    run.wait_for("Select your framework");
    run.press(&[DOWN, ENTER]); // Vite
    run.wait_for("Select services you'll use");
    // Supabase is the 6th item, Clerk the 12th (Down ×5, then ×6 more).
    run.press(&[DOWN, DOWN, DOWN, DOWN, DOWN, SPACE]);
    run.press(&[DOWN, DOWN, DOWN, DOWN, DOWN, DOWN, SPACE, ENTER]);
    run.wait_for("Select deployment/infrastructure");
    run.press(&[DOWN, SPACE, ENTER]); // vercel, the 2nd item
    run.wait_for("Generate .env files with these variables?");
    run.press(&["y", ENTER]);
    let (_, code) = run.finish();

    assert_eq!(code, 0);
    assert_eq!(
        example_body(d.path()),
        example_via_flags(&["--with", "vite,supabase,clerk,vercel"])
    );
}

