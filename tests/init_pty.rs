//! `evnx init`'s menus, driven through a real pseudo-terminal.
//!
//! # Why a pty
//!
//! Every prompt in `init` is a dialoguer widget, and dialoguer refuses a stdin
//! that is not a terminal (`IO error: not a terminal`). The four tests that used
//! to cover these menus fed keys through `assert_cmd`'s `write_stdin` (a pipe),
//! modelled the menus as numbered lists ("type 1, then 0"), and were
//! `#[ignore]`d with "run manually", which could not work either (T-001). They
//! are replaced by these, which press the same keys a person would.
//!
//! Unix only: the Windows console is a different mechanism, and `expectrl` is a
//! `cfg(unix)` dev-dependency.
//!
//! Tests named `known_*` pin a defect as it behaves in 0.10.0; the PR that fixes
//! it must flip the test (see `init_integration.rs` for the convention).
#![cfg(unix)]

use assert_cmd::cargo::cargo_bin_cmd;
use expectrl::{Eof, Expect, Session};
use std::path::Path;
use std::process::Command;
use std::time::Duration;
use tempfile::TempDir;

const ENTER: &str = "\r";
const DOWN: &str = "\x1b[B";
const SPACE: &str = " ";

/// The evnx binary under test, as cargo builds it for integration tests.
fn evnx_bin() -> &'static str {
    env!("CARGO_BIN_EXE_evnx")
}

/// One interactive `evnx init` in `dir`, on a 110×40 terminal, without colour.
struct Run {
    session: expectrl::session::OsSession,
}

impl Run {
    fn start(dir: &Path, args: &[&str]) -> Run {
        let mut cmd = Command::new(evnx_bin());
        cmd.current_dir(dir)
            .arg("init")
            .args(args)
            .env("NO_COLOR", "1")
            .env("TERM", "xterm");
        let mut session = Session::spawn(cmd).expect("spawn evnx in a pty");
        session.set_expect_timeout(Some(Duration::from_secs(15)));
        session
            .get_process_mut()
            .set_window_size(110, 40)
            .expect("set pty size");
        Run { session }
    }

    /// Wait until `text` has been printed; returns everything printed before it.
    fn wait_for(&mut self, text: &str) -> String {
        let found = self
            .session
            .expect(text)
            .unwrap_or_else(|e| panic!("never saw {text:?}: {e}"));
        String::from_utf8_lossy(found.before()).to_string()
    }

    /// Press keys one at a time, the way a person would. dialoguer reads one key
    /// per event, and a burst of escape sequences is not what it is built for.
    fn press(&mut self, keys: &[&str]) {
        for k in keys {
            self.session.send(k).expect("write to pty");
            std::thread::sleep(Duration::from_millis(40));
        }
    }

    /// Read to the end and return (remaining output, exit code).
    fn finish(mut self) -> (String, i32) {
        // ⚠️ `as_bytes`, not `before`: the `Eof` needle matches the whole
        // remaining buffer, so `before()` is always empty here.
        let rest = self.session.expect(Eof).expect("evnx did not exit");
        let rest = String::from_utf8_lossy(rest.as_bytes()).to_string();
        let status = self.session.get_process().wait().expect("wait for evnx");
        let code = match status {
            expectrl::process::unix::WaitStatus::Exited(_, code) => code,
            other => panic!("evnx did not exit normally: {other:?}"),
        };
        (rest, code)
    }
}

/// `.env.example` without the dated footer.
fn example_body(dir: &Path) -> String {
    std::fs::read_to_string(dir.join(".env.example"))
        .expect(".env.example written")
        .lines()
        .filter(|l| !l.starts_with("# Generated by evnx"))
        .collect::<Vec<_>>()
        .join("\n")
}

/// The same template written non-interactively, for comparison.
fn example_via_flags(args: &[&str]) -> String {
    let d = TempDir::new().unwrap();
    cargo_bin_cmd!("evnx")
        .current_dir(d.path())
        .arg("init")
        .args(args)
        .arg("--yes")
        .assert()
        .success();
    example_body(d.path())
}

