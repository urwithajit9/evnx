// ── strip_ansi ──────────────────────────────────────────────────────────────

#[test]
fn strip_ansi_removes_colour_cursor_and_osc_codes() {
    let raw =
        "\x1b[32m✓\x1b[0m Added\x1b[?25l\x1b[?25h \x1b]8;;https://x\x07link\x1b]8;;\x1b\\ done";
    assert_eq!(strip_ansi(raw), "✓ Added link done");
}

#[test]
fn strip_ansi_leaves_plain_text_alone() {
    let plain = "KEY=value [y/N] 100% — ünïcode";
    assert_eq!(strip_ansi(plain), plain);
}

// ── normalise (T-SHARE-37) ──────────────────────────────────────────────────

#[test]
fn normalise_replaces_the_temp_dir_in_every_spelling() {
    let p = Project::new();
    let raw = p.path().to_string_lossy().into_owned();
    let canonical = p
        .path()
        .canonicalize()
        .unwrap()
        .to_string_lossy()
        .into_owned();
    let text = format!("wrote {raw}/.env\nand {canonical}/.env.example\n");
    assert_eq!(
        normalise(&text, &[p.path()]),
        "wrote <dir>/.env\nand <dir>/.env.example\n"
    );
}

#[test]
fn normalise_replaces_dates_times_and_the_version() {
    let v = env!("CARGO_PKG_VERSION");
    let text = format!(
        "# Generated by evnx v{v} on 2026-10-14 09:30\n# Added by evnx add on 2026-10-14\nat 2026-10-14T09:30:05Z\r\n"
    );
    assert_eq!(
        normalise(&text, &[]),
        "# Generated by evnx v<version> on <date>\n# Added by evnx add on <date>\nat <date>Z\n"
    );
}

#[test]
fn normalise_does_not_take_numbers_that_are_not_dates() {
    // Too many digits on either side, or not a date shape at all.
    let text = "12026-10-14 2026-10-145 2026-1-14 port 6379 v1.2.3";
    assert_eq!(normalise(text, &[]), text);
}

#[test]
fn check_golden_accepts_a_match_and_rejects_a_difference() {
    let expected = "line one\nline two\n";
    check_golden("support/selftest.txt", expected);

    if std::env::var_os("UPDATE_GOLDEN").is_some() {
        return; // the mismatch below would be written as the new golden
    }
    let mismatch = std::panic::catch_unwind(|| {
        check_golden("support/selftest.txt", "line one\nline 2\n");
    });
    assert!(
        mismatch.is_err(),
        "a different text passed the golden check"
    );
}

// ── Project ─────────────────────────────────────────────────────────────────

#[test]
fn project_writes_nested_files_and_counts_lines() {
    let p = Project::new()
        .env("A=1\nA=2\n# A=3\n")
        .file("services/api/.env.example", "B=\n");
    assert_eq!(p.count_lines(".env", "A="), 2);
    assert_eq!(p.count_lines("services/api/.env.example", "B="), 1);
    assert_eq!(p.count_lines("missing", "A="), 0);
    assert!(p.exists("services/api"));
}

#[cfg(unix)]
#[test]
fn project_sets_modes_and_symlinks() {
    use std::os::unix::fs::PermissionsExt;
    let p = Project::new()
        .env("A=1\n")
        .mode(".env", 0o444)
        .symlink(".env", "link");
    let mode = std::fs::metadata(p.join(".env"))
        .unwrap()
        .permissions()
        .mode();
    assert_eq!(mode & 0o777, 0o444);
    assert_eq!(p.read("link"), "A=1\n");
}

// ── git (T-SHARE-32) ────────────────────────────────────────────────────────

#[test]
fn git_makes_a_real_repository_on_main() {
    let p = Project::new()
        .file(".gitignore", ".env\n")
        .env("A=1\n")
        .git();
    assert_eq!(
        p.git_cmd(&["rev-parse", "--is-inside-work-tree"]).trim(),
        "true"
    );
    assert_eq!(
        p.git_cmd(&["symbolic-ref", "--short", "HEAD"]).trim(),
        "main"
    );
    assert!(p.is_ignored(".env"));
    assert!(!p.is_ignored(".gitignore"));
    p.commit_all("first");
    assert_eq!(p.git_cmd(&["ls-files"]).trim(), ".gitignore");
    p.force_add(".env");
    assert!(p
        .git_cmd(&["diff", "--cached", "--name-only"])
        .contains(".env"));
}

#[test]
fn git_ignores_the_machines_own_configuration() {
    let p = Project::new().git();
    // GIT_CONFIG_GLOBAL points at an empty file: nothing global is visible,
    // whatever the developer's ~/.gitconfig holds.
    let global = p.git_cmd(&["config", "--global", "--list"]);
    assert!(global.trim().is_empty(), "global config leaked: {global}");
}

/// Why T-SHARE-32 exists: an empty `.git` directory is not a repository, and
/// git says so. A test that fakes one is not asking git anything.
#[test]
fn a_fake_dot_git_is_not_a_repository() {
    let p = Project::new().dir(".git").file(".gitignore", ".env\n");
    let out = std::process::Command::new("git")
        .current_dir(p.path())
        .args(["check-ignore", "-q", ".env"])
        .env("GIT_CONFIG_NOSYSTEM", "1")
        .env("GIT_CEILING_DIRECTORIES", p.path().parent().unwrap())
        .output()
        .expect("git is installed");
    assert_ne!(
        out.status.code(),
        Some(0),
        "git treated an empty .git as a repo"
    );
}

// ── run ─────────────────────────────────────────────────────────────────────

#[test]
fn run_reports_code_and_streams() {
    let p = Project::new();
    let out = run(p.path(), &["--version"]);
    out.assert_code(0)
        .assert_contains(env!("CARGO_PKG_VERSION"));
    let bad = run(p.path(), &["add", "service", "no_such_component", "--yes"]);
    bad.assert_code(2).assert_contains("unknown component");
}

/// `run` is what a script sees: no terminal. Piped bytes are not a terminal
/// either, which is why prompts need `support::pty`.
#[test]
fn run_has_no_terminal_even_with_piped_input() {
    let p = Project::new();
    let out = run_with(p.path(), &["add", "custom"], &[], Some(b"NAME\n"));
    assert_ne!(out.code, Some(0), "{}", out.all());
    assert!(!p.exists(".env.example"));
}

// ── both_renderers (T-SHARE-33) ─────────────────────────────────────────────

#[test]
fn both_renderers_agree_on_doctor() {
    let r = both_renderers(
        || {
            Project::new()
                .env("A=1\n")
                .example("A=\n")
                .file(".gitignore", ".env\n")
                .git()
        },
        &["doctor"],
        &["doctor", "--format", "json"],
    );
    let _: serde_json::Value =
        serde_json::from_str(&r.machine.stdout).expect("doctor --format json is JSON");
    assert!(
        r.changed.is_empty(),
        "doctor without --fix changed {:?}",
        r.changed
    );
}

#[test]
fn both_renderers_rejects_runs_that_change_different_files() {
    let caught = std::panic::catch_unwind(|| {
        both_renderers(
            Project::new,
            &["add", "service", "redis", "--yes"],
            &["--version"],
        )
    });
    assert!(
        caught.is_err(),
        "a write under one renderer only went unnoticed"
    );
}

// ── pty ─────────────────────────────────────────────────────────────────────

#[cfg(unix)]
#[test]
fn pty_drives_a_prompt_to_the_end() {
    use support::pty::{Pty, ENTER};
    let p = Project::new();
    let mut s = Pty::spawn(p.path(), &["add", "custom"]);
    s.wait_for("Variable name");
    s.press(&[ENTER]); // empty name: finish
    let (rest, code) = s.finish();
    assert_eq!(code, 0, "{rest}");
    assert!(rest.contains("No variables added"), "{rest}");
    assert!(!p.exists(".env.example"));
}
