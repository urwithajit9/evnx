fn read_env_example(dir: &std::path::Path) -> anyhow::Result<String> {
    std::fs::read_to_string(dir.join(".env.example")).map_err(|e| anyhow::anyhow!("{}", e))
}

/// `.env.example` without its `# Generated by evnx vX on YYYY-MM-DD HH:MM`
/// footer, for comparing runs.
///
/// ⚠️ The footer carries the minute. Four runs that straddle a minute boundary
/// differ in that line only, and the determinism tests failed on it — on the
/// Windows runner, where the runs are slower (T-074). Those tests are about
/// which blueprint and which variables, in which order; the clock is not part
/// of that.
fn without_generated_stamp(content: &str) -> String {
    content
        .lines()
        .filter(|l| !l.starts_with("# Generated by evnx v"))
        .collect::<Vec<_>>()
        .join("\n")
}

fn count_env_vars(content: &str) -> usize {
    content
        .lines()
        .filter(|l| {
            let t = l.trim();
            !t.is_empty() && !t.starts_with('#') && t.contains('=')
        })
        .count()
}

