#!/usr/bin/env python3
"""Measure the entropy thresholds `evnx scan` uses, over a fixed corpus (C4, RM-53).

The generic fallback reports a value of at least N characters whose Shannon
entropy (bits per character) is above T. Until 0.13.0 neither number had been
measured. This computes, for each (N, T), the share of secret-shaped positives
it reports (recall) and the share of known non-secrets it reports (false
positives), per class, and writes the table to docs/scan-thresholds.md.

Corpus, in tests/fixtures/entropy/:
  positives/<charset>-<length>.txt   random tokens, fixed seed: what a generic
                                     secret with no provider prefix looks like
  negatives/*.txt                    real strings that look random and are not
                                     secrets: npm SRI hashes, git SHAs,
                                     Cargo.lock checksums, UUIDs, base64 image
                                     data, minified identifiers

Entropy here is computed exactly as `heuristic::calculate_entropy` does since
the C4 step-0 fix: per character, divided by the character count.

    python3 scripts/measure-entropy.py            # rewrite the table
    python3 scripts/measure-entropy.py --check    # exit 1 if it would change
"""

import collections
import math
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
CORPUS = ROOT / "tests" / "fixtures" / "entropy"
OUT = ROOT / "docs" / "scan-thresholds.md"

LENGTHS = [20, 24, 32, 40]
THRESHOLDS = [round(4.0 + 0.1 * i, 1) for i in range(16)]  # 4.0 … 5.5


def entropy(s):
    if not s:
        return 0.0
    n = len(s)
    return -sum(c / n * math.log2(c / n) for c in collections.Counter(s).values())


def load(kind):
    out = {}
    for f in sorted((CORPUS / kind).glob("*.txt")):
        out[f.stem] = [l for l in f.read_text().splitlines() if l]
    return out


# The same filter as `heuristic::looks_like_key_material`: base64 / URL-safe
# characters only, and not an npm SRI hash.
KEY_MATERIAL = re.compile(r"^[A-Za-z0-9+/=_-]+$")
SRI = ("sha256-", "sha384-", "sha512-", "sha1-")


def judged(v):
    return KEY_MATERIAL.match(v) is not None and not v.startswith(SRI)


def rate(values, n, t):
    if not values:
        return 0.0
    return sum(1 for v in values if len(v) >= n and judged(v) and entropy(v) > t) / len(values)


def pct(x):
    return f"{100 * x:.0f}%"


def table():
    pos, neg = load("positives"), load("negatives")
    lines = [
        "# Scan entropy thresholds, measured",
        "",
        "Generated by `scripts/measure-entropy.py` from `tests/fixtures/entropy/`.",
        "Do not edit by hand: change the corpus or the script, then rerun it.",
        "`tests/scan_entropy.rs` pins the chosen thresholds against the same corpus.",
        "",
        "A value is reported when it has at least **N** characters, holds only",
        "base64 / URL-safe characters and is not an `sha*-` SRI hash",
        "(`looks_like_key_material`), and its Shannon entropy is above **T** bits",
        "per character.",
        "",
        "**Chosen (C4): N = 32, T = 4.3** (`ENTROPY_MIN_LEN`, `ENTROPY_MIN` in",
        "`src/core/secretscan/heuristic.rs`; the AWS secret-key check uses the same T).",
        "At 32 characters that reports 95% or more of random keys, from 40 all of",
        "them, and no hash, SHA, checksum, UUID or source token. Hex keys are never",
        "reported (their entropy is that of a SHA); provider rules catch those. Wrapped",
        "base64 lines stay reported: they cannot be told from a PEM key body. Was",
        "N = 32, T = 4.8, which reported 2–4% of 32-character keys.",
        "",
        "The token cut-off in `engine::extract_tokens` (more than 20 bytes) is below",
        "N, so it changes no result here.",
        "",
        "## Mean entropy per class",
        "",
        "| Class | Kind | Count | Mean length | Mean entropy | Max entropy |",
        "|---|---|---|---|---|---|",
    ]
    for kind, sets in (("positive", pos), ("negative", neg)):
        for name, vals in sets.items():
            es = [entropy(v) for v in vals]
            lines.append(
                f"| {name} | {kind} | {len(vals)} | "
                f"{sum(map(len, vals)) / len(vals):.0f} | {sum(es) / len(es):.2f} | {max(es):.2f} |"
            )
    for n in LENGTHS:
        lines += [
            "",
            f"## N = {n}: share reported, by threshold T",
            "",
            "| T | " + " | ".join(pos) + " | " + " | ".join(f"✗ {k}" for k in neg) + " |",
            "|---" * (1 + len(pos) + len(neg)) + "|",
        ]
        for t in THRESHOLDS:
            row = [pct(rate(v, n, t)) for v in pos.values()]
            row += [pct(rate(v, n, t)) for v in neg.values()]
            lines.append(f"| {t} | " + " | ".join(row) + " |")
    return "\n".join(lines) + "\n"


def main():
    text = table()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT.relative_to(ROOT)} is out of date: run scripts/measure-entropy.py")
            return 1
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
